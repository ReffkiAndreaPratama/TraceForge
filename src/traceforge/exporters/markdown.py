"""Markdown report export.

The Markdown report is a human-readable summary of a workspace.  It is built
from already-redacted data and never includes raw request or response bodies.
"""

from __future__ import annotations

from typing import Any

from traceforge.version import __version__


def _escape(value: Any) -> str:
    text = str(value)
    return text.replace("|", "\\|").replace("\n", " ")


def render_report(
    *,
    workspace_name: str,
    counts: dict[str, int],
    artifacts: list[Any],
    findings: list[Any],
    endpoints: list[Any],
    relationships: list[Any],
    include_limitations: bool = True,
) -> str:
    """Render a Markdown report for a workspace."""
    lines: list[str] = []
    lines.append(f"# TraceForge report - {workspace_name}")
    lines.append("")
    lines.append(f"Generated by TraceForge {__version__}.")
    lines.append("")

    lines.append("## Summary")
    lines.append("")
    lines.append("| Metric | Count |")
    lines.append("| --- | ---: |")
    for key in sorted(counts):
        lines.append(f"| {key} | {counts[key]} |")
    lines.append("")

    lines.append("## Artefacts")
    lines.append("")
    if artifacts:
        lines.append("| Name | Kind | Detected type | Size (bytes) | SHA-256 |")
        lines.append("| --- | --- | --- | ---: | --- |")
        for artifact in artifacts:
            lines.append(
                f"| {_escape(artifact.display_name)} | {_escape(artifact.kind)} | "
                f"{_escape(artifact.detected_type or 'unknown')} | {artifact.size_bytes} | "
                f"`{artifact.sha256}` |"
            )
    else:
        lines.append("_No artefacts have been imported yet._")
    lines.append("")

    lines.append("## Observed endpoints")
    lines.append("")
    if endpoints:
        lines.append("| Method | Origin | Path | Status codes | Observations |")
        lines.append("| --- | --- | --- | --- | ---: |")
        for endpoint in endpoints:
            codes = ", ".join(str(code) for code in (endpoint.status_codes_json or []))
            lines.append(
                f"| {_escape(endpoint.method)} | {_escape(endpoint.origin)} | "
                f"`{_escape(endpoint.path_key)}` | {codes or '-'} | {endpoint.count} |"
            )
    else:
        lines.append("_No endpoints have been observed yet._")
    lines.append("")

    lines.append("## Findings")
    lines.append("")
    if findings:
        lines.append("| Type | Summary | Confidence | Source |")
        lines.append("| --- | --- | --- | --- |")
        for finding in findings[:200]:
            lines.append(
                f"| {_escape(finding.type)} | {_escape(finding.summary)} | "
                f"{_escape(finding.confidence)} | `{_escape(finding.artifact_id or '-')}` |"
            )
        if len(findings) > 200:
            lines.append("")
            lines.append(f"_... and {len(findings) - 200} more findings._")
    else:
        lines.append("_No findings have been produced yet._")
    lines.append("")

    lines.append("## Evidence relationships")
    lines.append("")
    if relationships:
        lines.append("| Kind | From | To | Confidence | Verified |")
        lines.append("| --- | --- | --- | --- | --- |")
        for relationship in relationships[:200]:
            lines.append(
                f"| {_escape(relationship.kind)} | `{_escape(relationship.from_id)}` | "
                f"`{_escape(relationship.to_id)}` | {_escape(relationship.confidence)} | "
                f"{'yes' if relationship.verified else 'no'} |"
            )
        if len(relationships) > 200:
            lines.append("")
            lines.append(f"_... and {len(relationships) - 200} more relationships._")
    else:
        lines.append("_No relationships have been created yet._")
    lines.append("")

    if include_limitations:
        lines.append("## Limitations")
        lines.append("")
        lines.append(
            "- Endpoints are derived from observed traffic only; the tool cannot discover "
            "endpoints that were never captured."
        )
        lines.append(
            "- Path parameters are inserted by a documented heuristic and may be incorrect."
        )
        lines.append(
            "- A relationship between a binary and an endpoint is a hypothesis unless it is "
            "marked as verified."
        )
        lines.append(
            "- No dynamic analysis was performed; the tools were never executed."
        )
        lines.append("")

    return "\n".join(lines)
